def generate_scenarios():
    """
    Per scenario xi and period t draw independently:
      r_t^(xi) ~ U[FX_LOW, FX_HIGH]   exchange rate
      V_t^(xi) ~ U[V_MIN,  V_MAX]     ASM availability (kg)

    Derived quantities per scenario:
      lambda_t^(xi) = (gold_t * r_t^(xi) * C_TROY) / K_CONV
      I_t^(xi)      = lambda_t^(xi) * V_t^(xi)
      E_t^(xi)      = RHO * I_t^(xi)

    Gold price fixed at JP Morgan 2026 forecasts.
    p_sell = lambda (Option A).
    """
    n    = NUM_SCENARIOS
    fx   = np.random.uniform(FX_LOW, FX_HIGH, (n, T))
    vol  = np.random.uniform(V_MIN,  V_MAX,   (n, T))

    # CORRECTED: (gold * fx * C_TROY) / K_CONV
    cost   = gold_weekly[None, :] * fx * C_TROY / K_CONV
    inflow = cost * vol
    target = RHO * inflow
    probs  = np.ones(n) / n

    print(f"Scenarios ({n}, seed=42):")
    print(f"  FX range   : [{fx.min():.2f}, {fx.max():.2f}] GHS/USD")
    print(f"  Vol range  : [{vol.min():,.0f}, {vol.max():,.0f}] kg/week")
    print(f"  lambda range: GHS {cost.min():,.2f} – {cost.max():,.2f}/kg")
    print(f"  E_t range  : GHS {target.min()/1e9:.3f}bn – "
          f"{target.max()/1e9:.3f}bn/week\n")

    return cost, vol, fx, inflow, target, probs

# ─────────────────────────────────────────────────────────────
# SECTION 3 — DP solver
# ─────────────────────────────────────────────────────────────

def _run_single_dp(cost_xi, vol_xi, target_xi,
                   lambda_xi, lambda_mean_xi, p_sell_xi):
    """
    Parameters:
      lambda_xi      : (T,) period-specific buy cost for this scenario
      lambda_mean_xi : scalar mean buy cost for this scenario
      p_sell_xi      : (T,) transfer price for this scenario
                       (= lambda_xi for Option A)

    Terminal condition: -lambda_mean_xi * s_T
    Inventory reward:   -GAMMA * lambda_mean_xi * s_next
    Discrepancy:        E_t - p_sell_xi[t] * y_t
    Shortfall penalty:  PHI * lambda_mean_xi * shortfall (in forward sim)
    """
    inv_grid = np.linspace(0, S_BAR, INV_GRID_POINTS)
    n_inv    = len(inv_grid)
    V_dp     = np.full((T + 1, n_inv), np.inf)
    policy_x = np.zeros((T, n_inv))
    policy_y = np.zeros((T, n_inv))

    # Terminal condition
    for i, sv in enumerate(inv_grid):
        if sv >= R_MIN:
            V_dp[T][i] = -lambda_mean_xi * sv

    # Backward pass
    for t in reversed(range(T)):
        Et_xi    = target_xi[t]
        vol_t    = vol_xi[t]
        p_sell_t = p_sell_xi[t]   # period-specific transfer price
        x_grid   = np.linspace(0, vol_t, X_GRID_POINTS)

        for i, s_prev in enumerate(inv_grid):
            best_val = np.inf
            best_x   = 0.0
            best_y   = 0.0

            for xv in x_grid:
                avail  = s_prev + xv
                y_grid = np.linspace(0, min(avail, S_BAR),
                                     Y_GRID_POINTS)
                for yv in y_grid:
                    s_next = float(np.clip(avail - yv, 0.0, S_BAR))
                    j = min(int(round(s_next / S_BAR * (n_inv - 1))),
                            n_inv - 1)
                    if V_dp[t + 1][j] == np.inf:
                        continue

                    disc    = Et_xi - p_sell_t * yv
                    d_plus  = max(disc,  0.0)   # under-release
                    d_minus = max(-disc, 0.0)   # over-release

                    val = (ALPHA * d_plus + BETA * d_minus
                           - GAMMA * lambda_mean_xi * s_next
                           + V_dp[t + 1][j])
                    if val < best_val:
                        best_val = val
                        best_x   = xv
                        best_y   = yv

            V_dp[t][i]     = best_val if best_val < np.inf else np.inf
            policy_x[t][i] = best_x
            policy_y[t][i] = best_y

    obj    = V_dp[0][0]
    status = 'Optimal' if obj < np.inf else 'Infeasible'
    return V_dp, policy_x, policy_y, status, obj

# ─────────────────────────────────────────────────────────────
# SECTION 4 — Forward simulation
# ─────────────────────────────────────────────────────────────

def _simulate_forward(policy_x, policy_y, vol_xi, fx_xi,
                      target_xi, p_sell_xi, lambda_mean_xi):
    inv_grid  = np.linspace(0, S_BAR, INV_GRID_POINTS)
    n_inv     = len(inv_grid)
    s         = S0
    cum_purch = 0.0
    traj = {k: [] for k in [
        'inventory', 'purchase', 'release',
        'release_bog', 'release_market',
        'discrepancy', 'over_supply', 'under_supply',
        'cum_purchase']}

    for t in range(T):
        Et_xi = target_xi[t]
        vol_t = vol_xi[t]
        fx_t  = fx_xi[t]

        i      = min(int(round(s / S_BAR * (n_inv - 1))), n_inv - 1)
        x_pol  = float(np.clip(policy_x[t][i], 0.0, vol_t))
        avail  = s + x_pol
        y_pol  = float(np.clip(policy_y[t][i], 0.0, avail))
        s_next = float(np.clip(avail - y_pol, 0.0, S_BAR))
        cum_purch += x_pol

        # FX-threshold release routing
        if fx_t > FX_THRESHOLD:
            y_market = y_pol
            y_bog    = 0.0
        else:
            y_bog    = y_pol
            y_market = 0.0

        disc = Et_xi - p_sell_xi[t] * y_pol
        traj['inventory'].append(s_next)
        traj['purchase'].append(x_pol)
        traj['release'].append(y_pol)
        traj['release_bog'].append(y_bog)
        traj['release_market'].append(y_market)
        traj['discrepancy'].append(disc)
        traj['over_supply'].append(max(disc,  0.0))
        traj['under_supply'].append(max(-disc, 0.0))
        traj['cum_purchase'].append(cum_purch)
        s = s_next

    # Annual shortfall penalty (GANRAP mandate applies for 2026)
    shortfall_kg          = max(Q_ANNUAL - cum_purch, 0.0)
    traj['shortfall_kg']  = shortfall_kg
    traj['shortfall_ghs'] = PHI * lambda_mean_xi * shortfall_kg
    traj['final_inv']     = s
    return traj

