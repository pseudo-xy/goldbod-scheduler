# SECTION 5 — Stochastic DP (scenario decomposition)
# ─────────────────────────────────────────────────────────────

def solve_stochastic_dp(cost_scen, vol_scen, fx_scen,
                        inflow_scen, target_scen, probs):
    n_scen = len(probs)
    t0     = time.time()
    all_V  = []; all_px = []; all_py = []
    all_traj = []; results = []

    print(f"Solving {n_scen} scenarios (purchase + release)...")
    print(f"{'Scen':>5}  {'Status':>10}  {'Obj (GHS)':>20}  "
          f"{'Purch (kg)':>12}  {'Shortfall':>10}  {'Yr-end Inv':>12}")
    print("-" * 80)

    for xi in range(n_scen):
        # Scenario-specific lambda: JP Morgan price * scenario FX
        lambda_xi      = gold_weekly * fx_scen[xi] * C_TROY / K_CONV
        lambda_mean_xi = float(lambda_xi.mean())
        # Option A: p_sell = lambda (buy cost proxy)
        p_sell_xi      = lambda_xi.copy()

        V_dp, px, py, status_xi, obj_xi = _run_single_dp(
            cost_scen[xi], vol_scen[xi], target_scen[xi],
            lambda_xi, lambda_mean_xi, p_sell_xi)
        traj_xi = _simulate_forward(
            px, py, vol_scen[xi], fx_scen[xi],
            target_scen[xi], p_sell_xi, lambda_mean_xi)

        all_V.append(V_dp); all_px.append(px); all_py.append(py)
        all_traj.append(traj_xi)

        print(f"  {xi:>3d}  {status_xi:>10}  "
              f"{obj_xi:>20,.0f}  "
              f"{sum(traj_xi['purchase']):>12,.1f}  "
              f"{traj_xi['shortfall_kg']:>10,.1f}  "
              f"{traj_xi['final_inv']:>12,.1f}")

        disc_arr = (np.array(traj_xi['over_supply'])
                    + np.array(traj_xi['under_supply']))
        results.append({
            'Scenario':               xi,
            'Status':                 status_xi,
            'Yearend_Inventory_kg':   traj_xi['final_inv'],
            'Total_Purchase_kg':      sum(traj_xi['purchase']),
            'Total_Release_kg':       sum(traj_xi['release']),
            'Total_Release_BOG_kg':   sum(traj_xi['release_bog']),
            'Total_Release_Market_kg':sum(traj_xi['release_market']),
            'Shortfall_kg':           traj_xi['shortfall_kg'],
            'Shortfall_GHS':          traj_xi['shortfall_ghs'],
            'Total_Abs_Disc_GHS':     disc_arr.sum(),
            'Objective_GHS':          obj_xi,
            'Over_Supply_Periods':
                sum(1 for v in traj_xi['over_supply']  if v > 0),
            'Under_Supply_Periods':
                sum(1 for v in traj_xi['under_supply'] if v > 0),
        })

    solve_time = time.time() - t0
    df_scen    = pd.DataFrame(results)
    n_opt      = int((df_scen['Status'] == 'Optimal').sum())
    n_inf      = int(n_scen - n_opt)

    w           = probs
    inv_all     = np.array([t['inventory']      for t in all_traj])
    purch_all   = np.array([t['purchase']       for t in all_traj])
    release_all = np.array([t['release']        for t in all_traj])
    rel_bog_all = np.array([t['release_bog']    for t in all_traj])
    rel_mkt_all = np.array([t['release_market'] for t in all_traj])
    disc_all    = np.array([t['discrepancy']    for t in all_traj])
    cum_all     = np.array([t['cum_purchase']   for t in all_traj])

    inv_mean     = np.average(inv_all,     axis=0, weights=w)
    purch_mean   = np.average(purch_all,   axis=0, weights=w)
    release_mean = np.average(release_all, axis=0, weights=w)
    rel_bog_mean = np.average(rel_bog_all, axis=0, weights=w)
    rel_mkt_mean = np.average(rel_mkt_all, axis=0, weights=w)
    disc_mean    = np.average(disc_all,    axis=0, weights=w)
    cum_mean     = np.average(cum_all,     axis=0, weights=w)
    fx_mean      = np.average(fx_scen,     axis=0, weights=w)

    exp_obj = sum(probs[xi] * all_V[xi][0][0]
                  for xi in range(n_scen)
                  if all_V[xi][0][0] < np.inf)

    print(f"\nAll {n_scen} scenarios complete in {solve_time:.2f}s")
    print(f"Overall: {n_opt}/{n_scen} Optimal, {n_inf}/{n_scen} Infeasible\n")
    print("=" * 65)
    print("AGGREGATE RESULTS — GoldBod Stochastic DP (2026 Forward)")
    print("=" * 65)
    print(f"  Expected Objective (GHS)    : {exp_obj:>22,.0f}")
    print(f"  Mean Year-end Inventory (kg): "
          f"{df_scen['Yearend_Inventory_kg'].mean():>22,.1f}  "
          f"(Std: {df_scen['Yearend_Inventory_kg'].std():,.1f})")
    print(f"  Mean Total Purchase (kg)    : "
          f"{df_scen['Total_Purchase_kg'].mean():>22,.1f}  "
          f"[Q = {Q_ANNUAL:,.0f}]")
    print(f"  Mean Total Release (kg)     : "
          f"{df_scen['Total_Release_kg'].mean():>22,.1f}")
    print(f"    -> To BoG reserve (kg)    : "
          f"{df_scen['Total_Release_BOG_kg'].mean():>22,.1f}")
    print(f"    -> To market (kg)         : "
          f"{df_scen['Total_Release_Market_kg'].mean():>22,.1f}")
    print(f"  Mean Shortfall (kg)         : "
          f"{df_scen['Shortfall_kg'].mean():>22,.1f}  "
          f"(Std: {df_scen['Shortfall_kg'].std():,.1f})")
    print(f"  Scenarios meeting Q         : "
          f"{int((df_scen['Shortfall_kg']==0).sum()):>22d} / {n_scen}")
    print(f"  Mean Total Disc (GHS)       : "
          f"{df_scen['Total_Abs_Disc_GHS'].mean():>22,.0f}  "
          f"(Std: {df_scen['Total_Abs_Disc_GHS'].std():,.0f})")
    print(f"  Over-supply periods (avg)   : "
          f"{df_scen['Over_Supply_Periods'].mean():>22.1f}")
    print(f"  Under-supply periods (avg)  : "
          f"{df_scen['Under_Supply_Periods'].mean():>22.1f}")
    print(f"  Solve time (s)              : {solve_time:>22.2f}")
    print("=" * 65 + "\n")

    return {
        'exp_obj':      exp_obj,       'solve_time':    solve_time,
        'inv_mean':     inv_mean,      'purch_mean':    purch_mean,
        'release_mean': release_mean,  'rel_bog_mean':  rel_bog_mean,
        'rel_mkt_mean': rel_mkt_mean,  'disc_mean':     disc_mean,
        'cum_mean':     cum_mean,      'fx_mean':       fx_mean,
        'inv_all':      inv_all,       'purch_all':     purch_all,
        'release_all':  release_all,   'rel_bog_all':   rel_bog_all,
        'rel_mkt_all':  rel_mkt_all,   'df_scen':       df_scen,
        'all_V':        all_V,         'all_px':        all_px,
        'all_py':       all_py,        'lambda_mean':   lambda_mean,
        'lambda_arr':   lambda_arr,    'n_opt':         n_opt,
        'n_inf':        n_inf,
    }

